import { toWhatsappPhone } from './titan-phone.util';

describe('toWhatsappPhone', () => {
  it.each([
    ['11 2233-4455', '+5491122334455'],
    ['011 2233-4455', '+5491122334455'],
    ['011 15 2233-4455', '+5491122334455'],
    ['11 15 2233 4455', '+5491122334455'],
    ['+54 9 11 2233-4455', '+5491122334455'],
    ['+54 11 2233-4455', '+5491122334455'],
    ['5491122334455', '+5491122334455'],
    ['541122334455', '+5491122334455'],
    ['0054 9 11 2233 4455', '+5491122334455'],
    ['(0351) 15-412-3456', '+5493514123456'],
    ['0297 154 123456', '+5492974123456'],
    ['+598 99 123 456', '+59899123456'],
  ])('%s → %s', (raw, expected) => {
    expect(toWhatsappPhone(raw)).toBe(expected);
  });

  it.each([[''], [null], [undefined], ['abc'], ['4455-6677'], ['123']])(
    'devuelve null si no se puede interpretar sin adivinar: %p',
    (raw) => {
      expect(toWhatsappPhone(raw as string)).toBeNull();
    },
  );
});
